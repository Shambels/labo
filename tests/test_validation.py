"""Layer 2: sqlglot validation. Needs the sources (the schema of each comes from its catalog)."""
import pytest

from text2sql_calorvia.validation import validate


@pytest.mark.parametrize("source, sql", [
    ("compta", "DELETE FROM budget"),
    ("compta", "UPDATE budget SET montant = 0"),
    ("compta", "INSERT INTO budget (id_budget) VALUES (1)"),
    ("compta", "DROP TABLE budget"),
    ("compta", "TRUNCATE budget"),
    ("compta", "ALTER TABLE budget ADD COLUMN x int"),
    ("compta", "CREATE TABLE x (a int)"),
    ("compta", "SET default_transaction_read_only = off"),
    ("compta", "COPY budget TO STDOUT"),
    ("compta", "GRANT SELECT ON budget TO public"),
    ("compta", "BEGIN"),
    ("compta", "WITH d AS (DELETE FROM budget RETURNING *) SELECT * FROM d"),   # a write hidden in a CTE
    ("compta", "SELECT montant FROM budget FOR UPDATE"),
    ("compta", "SELECT pg_sleep(10)"),
    ("compta", "SELECT pg_read_file('/etc/passwd')"),
    ("compta", "SELECT lo_import('/etc/passwd')"),
    ("compta", "SELECT set_config('default_transaction_read_only', 'off', false)"),
    ("compta", "SELECT * FROM dblink('host=x', 'SELECT 1') AS t(a int)"),
    ("erp", "SELECT TOP 1 * INTO #t FROM PAR_CODE"),
    ("erp", "SELECT TOP 1 * INTO dbo.COPY_T FROM PAR_CODE"),
    ("erp", "EXEC sp_configure"),
    ("erp", "EXEC xp_cmdshell 'whoami'"),
    ("erp", "SELECT * FROM OPENROWSET('SQLNCLI', 'Server=x;', 'SELECT 1')"),
    ("erp", "SELECT 1; DELETE FROM PAR_CODE"),
    ("erp", "SELECT 1; SELECT 2"),
    ("erp", "MERGE INTO PAR_CODE USING SOC_SITE ON 1 = 0 WHEN MATCHED THEN DELETE;"),
])
def test_anything_but_one_read_is_refused(sources, source, sql):
    v = validate(source, sql)
    assert not v.ok and v.errors and v.sql is None


def test_a_read_passes_with_its_own_text(sources):
    sql = "SELECT CLI_NOM, CLI_TYPE FROM CLI_CLIENT WHERE CLI_ACTIF = 1 ORDER BY CLI_NOM;"
    v = validate("erp", sql)
    assert v.ok and v.tables == ["CLI_CLIENT"]
    assert v.sql == sql.rstrip(";")   # never regenerated by sqlglot; SQL Server's limit is SET ROWCOUNT


def test_postgres_gets_a_limit_only_when_it_has_none(sources):
    assert validate("compta", "SELECT numero_compte FROM plan_comptable", max_rows=50).sql.endswith("LIMIT 51")
    assert validate("compta", "SELECT numero_compte FROM plan_comptable LIMIT 3").sql.endswith("LIMIT 3")


@pytest.mark.parametrize("source, sql, expected", [
    ("erp", "SELECT CLI_NOMX FROM CLI_CLIENT", "Colonne inconnue : CLI_NOMX. Colonnes proches : CLI_CLIENT.CLI_NOM"),
    ("erp", "SELECT CLI_NOM FROM CLIENT", "Tables proches : CLI_CLIENT"),
    ("erp", "SELECT numero_compte FROM plan_comptable", "Elle est dans la source compta"),
    ("paie", "SELECT national_number FROM employees", "Colonne non lisible : employees.national_number"),
    ("paie", "SELECT * FROM employees", "SELECT * refusé sur employees"),
    ("paie", "SELECT e.* FROM employees e", "SELECT * refusé sur employees"),
    ("compta", "SELEC 1", "Erreur de syntaxe postgres (ligne 1"),
    ("erp", "SELECT TOP 5 FROM CLI_CLIENT", "SELECT sans colonne"),   # sqlglot parses it; the server wouldn't
    ("paie", "SELECT employee_id, gross_amount FROM payslips", "Règle de confidentialité"),
    ("nope", "SELECT 1", "Source inconnue"),
])
def test_errors_are_written_for_the_model(sources, source, sql, expected):
    v = validate(source, sql)
    assert not v.ok
    assert expected in " ".join(v.errors)


def test_dialects_are_not_mixed(sources):
    assert validate("erp", "SELECT TOP 3 CLI_NOM FROM CLI_CLIENT").ok
    assert not validate("compta", "SELECT TOP 3 numero_compte FROM plan_comptable").ok


def test_payroll_aggregate_carries_the_group_size_check(sources):
    v = validate("paie", "SELECT AVG(gross_amount) FROM payslips")
    assert v.ok and v.privacy_check.startswith("SELECT MIN(n_people)")
    assert validate("paie", "SELECT COUNT(*) FROM payslips").privacy_check is None


def test_count_star_reads_no_column_and_passes_on_a_partly_hidden_table(sources):
    # Found by step 14's evaluation (P01): COUNT(*) was refused as a SELECT * on employees
    assert validate("paie", "SELECT exit_reason, COUNT(*) FROM employees GROUP BY exit_reason").ok
    assert validate("paie", "SELECT COUNT(*) FROM employees WHERE exit_date IS NOT NULL").ok


# Step 21 (D69): joins that multiply what is counted or summed
ENTRY_LINES = "FROM ecriture e JOIN ligne_ecriture l ON l.id_ecriture = e.id_ecriture"


@pytest.mark.parametrize("source, sql, word", [
    ("compta", f"SELECT COUNT(*), SUM(l.debit) {ENTRY_LINES} WHERE e.statut = 'BROUILLARD'", "COUNT(DISTINCT e.id_ecriture)"),
    ("compta", f"SELECT COUNT(1) {ENTRY_LINES}", "COUNT(DISTINCT e.id_ecriture)"),
    ("compta", "SELECT COUNT(*) FROM ecriture e, ligne_ecriture l WHERE l.id_ecriture = e.id_ecriture", "COUNT(DISTINCT"),
    ("erp", "SELECT SUM(f.FAC_MT_HT) FROM VTE_FACT f JOIN VTE_FACT_LIG l ON l.FAC_ID = f.FAC_ID", "f.fac_mt_ht"),
    ("paie", "SELECT COUNT(*) FROM payslips p JOIN payslip_lines l USING (payslip_id)", "COUNT(DISTINCT p.payslip_id)"),
])
def test_a_join_that_multiplies_rows_gets_a_warning(sources, source, sql, word):
    result = validate(source, sql)
    assert result.ok and any(word in w for w in result.warnings)
    assert result.as_dict()["warnings"] == result.warnings


@pytest.mark.parametrize("source, sql", [
    ("compta", f"SELECT COUNT(DISTINCT e.id_ecriture), SUM(l.debit) {ENTRY_LINES}"),
    ("compta", "SELECT COUNT(*) FROM ligne_ecriture l JOIN ecriture e ON e.id_ecriture = l.id_ecriture"),   # lines
    ("compta", f"SELECT e.code_journal, COUNT(*) {ENTRY_LINES} GROUP BY e.code_journal"),                   # per parent
    ("erp", "SELECT SUM(l.FL_MT_HT) FROM VTE_FACT f JOIN VTE_FACT_LIG l ON l.FAC_ID = f.FAC_ID"),
    ("paie", "SELECT COUNT(*) FROM payslips p JOIN payroll_runs r ON r.run_id = p.run_id"),
    ("erp", "SELECT COUNT(*) FROM VTE_FACT"),
])
def test_a_join_that_does_not_multiply_gets_no_warning(sources, source, sql):
    result = validate(source, sql)
    assert result.ok and result.warnings == []
