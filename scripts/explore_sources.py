"""Write the schema of the three sources to docs/sources/<source>.md: tables, row counts, columns, keys, comments.

Schema only, no data values: the repository is public and the payroll holds (fictional) personal data.

    uv run python scripts/explore_sources.py
"""
from pathlib import Path

from text2sql_calorvia.catalog import describe
from text2sql_calorvia.sources import SOURCES

OUT = Path("docs/sources")


def cell(value):
    """A value safe inside a Markdown table cell."""
    return "" if value is None else str(value).replace("|", "\\|").replace("\n", " ")


def to_markdown(source, tables):
    total = sum(t["rows"] for t in tables)
    lines = [
        f"# {source.label} (`{source.database}`, {source.engine}, dialect `{source.dialect}`)",
        "",
        "Generated by `scripts/explore_sources.py` from the database catalog, as `agent_ro`. Do not edit by hand.",
        "",
        f"{len(tables)} tables, {total:,} rows.".replace(",", " "),
        "",
        "| Table | Rows | Columns | Comment |",
        "|---|---:|---:|---|",
    ]
    for t in tables:
        lines.append(f"| `{t['table_name']}` | {t['rows']} | {len(t['columns'])} | {cell(t['comment'])} |")
    for t in tables:
        lines += ["", f"## `{t['table_name']}` ({t['rows']} rows)", ""]
        if t["comment"]:
            lines += [t["comment"], ""]
        for key in t["keys"]:
            lines.append(f"- {key['kind']}: `{key['definition']}`")
        if t["keys"]:
            lines.append("")
        lines += ["| Column | Type | Null | Readable | Comment |", "|---|---|---|---|---|"]
        for c in t["columns"]:
            readable = "yes" if c["readable"] else "**no**"
            null = "yes" if c["nullable"] else "no"
            lines.append(f"| `{c['column_name']}` | {c['data_type']} | {null} | {readable} | {cell(c['comment'])} |")
    return "\n".join(lines) + "\n"


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    for name, source in SOURCES.items():
        tables = describe(name)
        (OUT / f"{name}.md").write_text(to_markdown(source, tables), encoding="utf-8")
        hidden = sum(not c["readable"] for t in tables for c in t["columns"])
        print(f"{name}: {len(tables)} tables, {sum(t['rows'] for t in tables)} rows, "
              f"{sum(len(t['columns']) for t in tables)} columns ({hidden} not readable by agent_ro)")


if __name__ == "__main__":
    main()
